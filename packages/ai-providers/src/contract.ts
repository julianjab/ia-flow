/** Sandbox context a tool executes in. Mirrors apps/server's
 *  `tools/index.ts::ToolContext` field-for-field, except `policy`, which
 *  this package treats as opaque (it's forwarded, never read, here) — the
 *  concrete `ToolContext` (with a real `CompiledPolicy`) is structurally
 *  assignable wherever this type is expected. */
export interface ToolContext {
  repoPaths: Record<string, string>
  sourceContext?: unknown
  fileSimplifierEnabled?: boolean
  writePaths?: string[]
  taskId?: string
  policy?: unknown
}

export interface LoopOptions {
  onToolCall?: (name: string, input: unknown, toolUseId: string) => void
  onToolResult?: (name: string, result: string, toolUseId: string) => void
  signal?: AbortSignal
  logContext?: Record<string, unknown>
  /** See `LoopOptions.maxPauseTurnRetries` in packages/tools/src/contract.ts
   *  (the implementation's copy of this type) for the full rationale. */
  maxPauseTurnRetries?: number
  /** See `LoopOptions.retryTruncatedToolUse` in packages/tools/src/contract.ts
   *  (the implementation's copy of this type) for the full rationale. */
  retryTruncatedToolUse?: boolean
}

export interface LoopResult {
  text: string
  iters: number
  stopReason: string
  truncated: boolean
  usage: RunUsage
  toolCalls: number
  toolErrors: number
}

export interface ToolDefinitionsOptions {
  providerKind?: ProviderKind
  toolNames?: string[]
}

/** The agentic tool-execution engine, injected so `anthropic-api` never
 *  imports apps/server's tool registry directly. */
export interface ToolExecutionPort {
  getToolDefinitions(
    opts?: ToolDefinitionsOptions,
  ): Array<{ name: string; description: string; input_schema: object }>
  executeLoop(
    // `overrides` mirrors `FetchApiOverrides` in packages/tools/src/engine.ts
    // (kept `any`-shaped here, like the rest of this port, to avoid a
    // cross-package type import for a single internal knob).
    fetchApi: (messages: any[], overrides?: { bumpMaxTokens?: boolean }) => Promise<any>,
    initialMessages: any[],
    ctx: ToolContext,
    opts?: LoopOptions,
  ): Promise<LoopResult>
}

